function parseArgs(argv) {
  if (argv[0] === "assemble") {
    const rest = argv.slice(1);
    for (const arg of rest) {
      if (arg !== "--check" && arg !== "--force" && arg !== "--dry-run") {
        throw new Error(`unknown argument for assemble: ${arg}\n\n${HELP}`);
      }
    }
    return { command: "assemble", check: rest.includes("--check") };
  }

  const targets = new Set();
  let force = false;
  let dryRun = false;
  let user = false;

  for (const arg of argv) {
    switch (arg) {
      case "--opencode":
      case "opencode":
        targets.add("opencode");
        break;
      case "--omos":
      case "omos":
        targets.add("omos");
        break;
      case "--claude":
      case "claude":
        targets.add("claude");
        break;
      case "--zcode":
      case "zcode":
        targets.add("zcode");
        break;
      case "--dsh":
      case "dsh":
        targets.add("dsh");
        break;
      case "--user":
        user = true;
        break;
      case "--force":
        force = true;
        break;
      case "--dry-run":
        dryRun = true;
        break;
      case "-h":
      case "--help":
        return { help: true };
      default:
        throw new Error(`unknown argument: ${arg}\n\n${HELP}`);
    }
  }

  if (targets.has("opencode") && targets.has("omos")) {
    throw new Error(`--omos cannot be combined with --opencode; --opencode already installs the omos way when a user-level omos install is detected\n\n${HELP}`);
  }

  if (targets.size === 0) {
    targets.add("opencode");
    targets.add("claude");
  }
  return { targets, force, dryRun, user };
}

function walk(root, dir, onFile) {
  for (const name of readdirSync(dir)) {
    if (isSkipped(name)) continue;
    const full = join(dir, name);
    if (statSync(full).isDirectory()) walk(root, full, onFile);
    else onFile(full);
  }
}

/**
 * Copy one file with skip/force/dry-run semantics. displayRoot/displayPrefix
 * only control how the destination is displayed (user-level installs pass the
 * home directory and "~/"); defaults keep the project-relative display.
 */
function copyOne(src, dest, { force, dryRun, displayRoot = process.cwd(), displayPrefix = "" }, counts) {
  const rel = displayPrefix + relative(displayRoot, dest);
  const exists = existsSync(dest);

  if (exists && !force) {
    counts.skipped++;
    console.log(`  skip       ${rel}  (exists, use --force to overwrite)`);
    return;
  }
  if (!dryRun) {
    mkdirSync(dirname(dest), { recursive: true });
    copyFileSync(src, dest);
  }
  counts[exists ? "overwritten" : "created"]++;
  console.log(`  ${exists ? "overwrite" : "create   "}  ${rel}${dryRun ? "  (dry-run)" : ""}`);
}

/**
 * Write generated content with the same skip/force/dry-run semantics as copyOne.
 * displayRoot/displayPrefix only control how the destination is displayed
 * (the user-level ZCode target passes the home directory and "~/"); defaults
 * keep the project-relative display for all existing callers.
 */
function writeAgent(dest, content, { force, dryRun, displayRoot = process.cwd(), displayPrefix = "" }, counts) {
  const rel = displayPrefix + relative(displayRoot, dest);
  const exists = existsSync(dest);

  if (exists && !force) {
    counts.skipped++;
    console.log(`  skip       ${rel}  (exists, use --force to overwrite)`);
    return;
  }
  if (!dryRun) {
    mkdirSync(dirname(dest), { recursive: true });
    writeFileSync(dest, content);
  }
  counts[exists ? "overwritten" : "created"]++;
  console.log(`  ${exists ? "overwrite" : "create   "}  ${rel}${dryRun ? "  (dry-run)" : ""}`);
}

/**
 * Copy a set's entries under targetRoot/dest. dest is the scope's destination
 * subdirectory: ".opencode"/".claude" at project level, "" at user level
 * (files land directly in the user-level config root).
 */
function copyEntries(set, entries, targetRoot, dest, opts, counts) {
  if (!existsSync(set.from)) {
    console.warn(`warn: source directory for '${set.dest}' is missing in this installation, skipped`);
    return;
  }

  for (const entry of entries) {
    const src = join(set.from, entry);
    if (!existsSync(src)) {
      console.warn(`warn: missing entry '${entry}' in ${set.dest} source, skipped`);
      continue;
    }
    if (statSync(src).isDirectory()) {
      walk(src, src, (fileAbs) =>
        copyOne(fileAbs, join(targetRoot, dest, entry, relative(src, fileAbs)), opts, counts),
      );
    } else {
      copyOne(src, join(targetRoot, dest, entry), opts, counts);
    }
  }
}

/** True when an omos install already exists at user level (~/.config/opencode). */
function omosUserLevelPresent() {
  const cfgDir = join(homedir(), ".config", "opencode");
  if (existsSync(join(cfgDir, "node_modules", OMOS_PACKAGE))) return true;
  for (const name of ["opencode.json", "opencode.jsonc"]) {
    const file = join(cfgDir, name);
    if (existsSync(file) && readFileSync(file, "utf8").includes(OMOS_PACKAGE)) return true;
  }
  return false;
}

/** True when the OpenCode app is installed (an `opencode` binary on PATH). */
function opencodeInstalled() {
  const result = spawnSync("opencode", ["--version"], { stdio: "ignore" });
  return !(result.error && result.error.code === "ENOENT");
}

/**
 * Assemble one agent markdown file for a backend: its frontmatter lines from
 * agents/backends/<backend>.json joined with the shared prompt body from
 * agents/prompts/<name>.md (which carries the omos attribution notice).
 */
function loadBackend(name) {
  return JSON.parse(readFileSync(join(PKG_ROOT, "agents", "backends", name, "agents.json"), "utf8"));
}

/**
 * Read one shared prompt body verbatim; a backend template may only reference
 * prompts that exist. This is the raw body of ONE agent, before the omos
 * attribution notice is dropped and the universal disciplines appended — every
 * delivery path of a prompt starts here.
 */
function promptBody(agentName) {
  const file = join(PKG_ROOT, "agents", "prompts", `${agentName}.md`);
  if (!existsSync(file)) {
    throw new Error(`agents/prompts/${agentName}.md is missing (referenced by a backend template)`);
  }
  return readFileSync(file, "utf8");
}

/**
 * The attribution notice every adapted prompt body opens with, verbatim.
 * Provenance belongs in the SOURCE and the README, not in the text an agent is
 * given: the notice is a licence statement, and a licence statement has no
 * addressee inside a system prompt.
 */
const ATTRIBUTION_NOTICE =
  "> Adapted from [oh-my-opencode-slim](https://github.com/alvinunreal/oh-my-opencode-slim) agent prompts — MIT License, Copyright (c) 2025.";

/**
 * Drop the attribution notice from the head of a prompt body. Exactly one
 * optional leading notice and the blank line after it go; nothing else is
 * touched. A body without the notice passes through unchanged, and a body that
 * merely mentions oh-my-opencode-slim mid-prompt keeps that mention.
 *
 * @param {string} body - a raw shared prompt body.
 * @returns {string} the delivered text, notice removed.
 */
function stripAttribution(body) {
  const head = `${ATTRIBUTION_NOTICE}\n\n`;
  return body.startsWith(head) ? body.slice(head.length) : body;
}

/** Load a backend's slot texts: agents/backends/<backend>/slots/<name>.md -> Map(name -> trimmed content). */
function loadSlots(backendName) {
  const dir = join(PKG_ROOT, "agents", "backends", backendName, "slots");
  const slots = new Map();
  if (!existsSync(dir)) return slots;
  for (const file of readdirSync(dir)) {
    if (!file.endsWith(".md")) continue;
    slots.set(file.replace(/\.md$/, ""), readFileSync(join(dir, file), "utf8").replace(/\s+$/, ""));
  }
  return slots;
}

/**
 * Replace {{slot:<name>}} placeholders with the backend's slot texts. A slot
 * referenced by the body but missing for this backend is a hard error — backends
 * must define every slot the shared prompts reference. Slot names used by the
 * body are recorded in usedSlots so loop callers can warn about unused slots.
 */
function fillSlots(body, backendName, usedSlots) {
  const slots = loadSlots(backendName);
  return body.replace(SLOT_RE, (raw, slotName) => {
    if (!slots.has(slotName)) {
      throw new Error(`agents/backends/${backendName}/slots/ is missing slot '${slotName}' (referenced by agents/prompts/)`);
    }
    usedSlots.add(slotName);
    return slots.get(slotName);
  });
}

/** Warn about slot files no prompt body of this assemble run referenced. */
function warnUnusedSlots(backendName, usedSlots) {
  for (const slotName of loadSlots(backendName).keys()) {
    if (!usedSlots.has(slotName)) console.warn(`warn: unused slot '${slotName}' in agents/backends/${backendName}/slots/`);
  }
}

/**
 * Assemble one agent markdown file for a backend: its frontmatter lines from
 * agents/backends/<backend>.json joined with the shared prompt body from
 * agents/prompts/<name>.md (which carries the omos attribution notice), with
 * {{slot:...}} placeholders filled from the backend's slots/ and the universal
 * disciplines appended last — a delivered agent prompt is body + disciplines,
 * the same pair every other backend delivers.
 */
function assembleAgent(backendName, name, usedSlots) {
  const meta = loadBackend(backendName).agents[name];
  if (!meta) throw new Error(`agents/backends metadata is missing agent '${name}'`);
  const body = fillSlots(stripAttribution(promptBody(name)), backendName, usedSlots).replace(/^\s+/, "").replace(/\s+$/, "");
  return `---\n${meta.frontmatter.join("\n")}\n---\n\n${body}${disciplinesBlock()}`;
}

// ── the universal disciplines ───────────────────────────────────────────────

/**
 * The universal disciplines as delivered text: agents/disciplines.md, verbatim,
 * with the blank-line separator that appends it to an agent body. They live in
 * their own shared file rather than inside one agent's prompt, because every
 * agent carries them — the orchestrator included.
 * @returns {string} the appended block, without a trailing newline.
 */
function disciplinesBlock() {
  const file = join(PKG_ROOT, "agents", "disciplines.md");
  if (!existsSync(file)) throw new Error("agents/disciplines.md is missing (the universal disciplines every agent prompt carries)");
  return "\n\n" + readFileSync(file, "utf8").replace(/\s+$/, "");
}

/**
 * Deliver one agent's prompt with the universal disciplines appended.
 *
 * The disciplines used to reach a specialist only when the orchestrator copied
 * them into every delegation brief: that put a fixed block on every dispatch —
 * cost proportional to briefs, not to sessions — and made correctness depend on
 * the orchestrator obeying a copy instruction. Every agent now carries them in
 * its own prompt: authored once, delivered by every backend (the markdown
 * backends inline the body, DSH delivers it as the preset persona and as each
 * lane's persona), and paid for once per session instead of once per brief.
 *
 * Appended at the END of the body, deliberately: the disciplines are the last
 * thing the agent reads, they leave every persona's opening intact, and the
 * result stays a mechanical comparison for `--check`. Slots are filled BEFORE
 * the append in every path, so a `{{slot:...}}` inside a body is always
 * substituted first.
 *
 * @param {string} agentName - shared prompt name (file base name, or a lane key).
 * @returns {string} prompt text; no trailing newline, as prompt readers expect.
 */
function agentPromptBody(agentName) {
  return stripAttribution(promptBody(agentName)).replace(/^\s+/, "").replace(/\s+$/, "") + disciplinesBlock();
}

/**
 * Assemble every agent of a backend into outDir with copyOne semantics. When
 * usedSlots is omitted the backend owns slot accounting and warns about
 * unused slots; callers that render additional backend content (e.g. the
 * zcode AGENTS.md) pass a shared set and warn themselves once, after all
 * consumers have run.
 */
function assembleBackend(name, outDir, opts, counts, usedSlots) {
  const backend = loadBackend(name);
  const slots = usedSlots ?? new Set();
  for (const agentName of Object.keys(backend.agents).sort()) {
    writeAgent(join(outDir, `${agentName}.md`), assembleAgent(name, agentName, slots), opts, counts);
  }
  if (usedSlots === undefined) warnUnusedSlots(name, slots);
}

