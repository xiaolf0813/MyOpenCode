/**
 * Structural validation of the lane settings page. This is the package that
 * reaches the browser, so the checks are the ones whose failure would only show
 * up in a running GUI: the declaration `dsh-client-modules` scans for, the
 * export it resolves, the classic-script registration seam, a module id that
 * matches the package name, and a `require` list inside the shell's seed table.
 *
 * @returns {string[]} human-readable problems; empty means valid.
 */
function laneUiPluginProblems() {
  const problems = [];
  const manifest = laneUiManifest();

  // dsh-client-modules:648-655 reads exactly this pair, and throws on a
  // declaration whose "./client" export is missing.
  const client = manifest.dsh !== null && typeof manifest.dsh === "object" ? manifest.dsh.client : undefined;
  if (client === null || typeof client !== "object") {
    problems.push("lane-plugin-ui/package.json declares no dsh.client, so the page would never be scanned");
  } else if (client.platform !== "web") {
    problems.push(`lane-plugin-ui/package.json dsh.client.platform is ${JSON.stringify(client.platform)}, not "web"`);
  }
  const exportsField = manifest.exports ?? {};
  const clientTarget = exportsField["./client"];
  if (typeof clientTarget !== "string") {
    problems.push("lane-plugin-ui/package.json exports no './client', so dsh-client-modules would refuse the package");
  } else if (!existsSync(join(DSH_LANE_UI_SRC, clientTarget))) {
    problems.push(`lane-plugin-ui/package.json exports './client' -> '${clientTarget}', which does not exist`);
  }
  const hostTarget = exportsField["."];
  if (typeof hostTarget !== "string" || !existsSync(join(DSH_LANE_UI_SRC, hostTarget))) {
    problems.push(`lane-plugin-ui/package.json exports '.' -> ${JSON.stringify(hostTarget)}, which does not exist`);
  }

  if (clientTarget === undefined || typeof clientTarget !== "string") return problems;
  const bundle = readFileSync(join(DSH_LANE_UI_SRC, clientTarget), "utf8");

  // The only registration seam the browser module table accepts.
  if (!bundle.includes("window.__ModuleLoader__.load(")) {
    problems.push("lane-plugin-ui/lib/client.js does not register through window.__ModuleLoader__.load(...)");
  }
  if (!/\bfactory\s*:/.test(bundle)) {
    problems.push("lane-plugin-ui/lib/client.js declares no factory, so the module table cannot materialize it");
  }

  // The bundle registers under the name the module table keys it by.
  const idMatch = /id:\s*['"]([^'"]+)['"]/.exec(bundle);
  if (idMatch === null) problems.push("lane-plugin-ui/lib/client.js does not declare a module id");
  else if (idMatch[1] !== manifest.name) {
    problems.push(`lane-plugin-ui/lib/client.js registers id '${idMatch[1]}' but the package is named '${manifest.name}'`);
  }

  // Only the nine seed specifiers resolve in the browser module table.
  for (const [, spec] of bundle.matchAll(/\brequire\(\s*['"]([^'"]+)['"]\s*\)/g)) {
    if (!CLIENT_SEED_MODULES.has(spec)) {
      problems.push(
        `lane-plugin-ui/lib/client.js requires '${spec}', which is not one of the browser shell's ${CLIENT_SEED_MODULES.size} seed modules (it would fail at runtime with "missed the module table")`,
      );
    }
  }

  return problems;
}

/**
 * Validate the lane settings page's HOST half by importing it. It is inert by
 * design, has no imports of its own, and is never executed by anything else —
 * so loading it here is the cheapest honest proof that a profile row naming it
 * resolves and that the half registers nothing.
 *
 * @returns {Promise<string | undefined>} a problem description, or undefined when valid.
 */
async function laneUiHostProblem(file) {
  let mod;
  try {
    mod = await import(pathToFileURL(file).href);
  } catch (err) {
    return `the host half does not import: ${err.message}`;
  }
  if (mod.name !== laneUiManifest().name) return `the host half exports name ${JSON.stringify(mod.name)}, which does not match the package name`;
  if (!Array.isArray(mod.inject) || mod.inject.length !== 0) {
    return `the host half must inject nothing (got ${JSON.stringify(mod.inject)}); the profile row must not wait on a service`;
  }
  if (typeof mod.apply !== "function") return "the host half exports no apply function";
  try {
    const result = mod.apply({});
    if (result !== undefined) return "the host half's apply must be inert, but it returned a value";
  } catch (err) {
    return `the host half's apply is not inert: ${err.message}`;
  }
  return undefined;
}

